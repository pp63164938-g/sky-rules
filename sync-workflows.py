def get_config_source_path(value: object, config_path: Path) -> Path:
    """解析外部配置中的源路径，默认相对仓库根目录。"""
    if not value:
        raise ValueError(f"{config_path.name}: target.source 不能为空")

    return resolve_path(str(value), ROOT)


def get_config_target_path(item: dict[str, object], config_path: Path) -> Path:
    """解析外部配置中的目标路径，环境变量优先于默认 target。"""
    for env_name in as_list(item.get("target_env") or item.get("exact_env")):
        value = os.environ.get(env_name)
        if value:
            return resolve_path(value)

    target = item.get("target")
    if not target:
        raise ValueError(f"{config_path.name}: target.target 不能为空")

    return resolve_path(str(target), ROOT)


def is_file_mode(mode: str) -> bool:
    """判断同步模式是否输出到单文件。"""
    return mode in {"file", "assembled_rules", "codex_rules"}


def normalize_config_target(item: object, config_path: Path) -> dict[str, object]:
    """将外部 JSON target 规范化成脚本内部同步目标结构。"""
    if not isinstance(item, dict):
        raise ValueError(f"{config_path.name}: targets 必须是对象数组")

    mode = str(item.get("mode", "")).strip()
    if mode not in {"mirror", "file", "assembled_rules", "codex_rules", "agents_skills"}:
        raise ValueError(f"{config_path.name}: 不支持的 mode: {mode}")

    name = str(item.get("name", "")).strip()
    if not name:
        raise ValueError(f"{config_path.name}: target.name 不能为空")

    src = get_config_source_path(item.get("source"), config_path)
    dst = get_config_target_path(item, config_path)
    exact_env = as_list(item.get("target_env") or item.get("exact_env"))
    base_env = as_list(item.get("base_env"))

    if item.get("detect"):
        detect = resolve_path(str(item["detect"]), ROOT)
    elif is_file_mode(mode):
        detect = dst.parent
    else:
        detect = dst

    target: dict[str, object] = {
        "name": name,
        "src": src,
        "dst": dst,
        "mode": mode,
        "pattern": str(item.get("pattern", "*.md")),
        "exclude": as_list(item.get("exclude")),
        "exact_env": exact_env,
        "base_env": base_env,
        "detect": detect,
        "config": config_path.name,
    }

    return target


def load_config_targets() -> list[dict[str, object]]:
    """读取 sync-targets*.json 扩展同步目标配置。"""
    targets: list[dict[str, object]] = []
    for config_path in CONFIG_TARGET_FILES:
        if not config_path.exists():
            continue

        try:
            raw_config = json.loads(config_path.read_text(encoding="utf-8"))
            raw_targets = raw_config.get("targets", raw_config) if isinstance(raw_config, dict) else raw_config
            if not isinstance(raw_targets, list):
                raise ValueError("根节点必须是数组，或包含 targets 数组")

            for raw_target in raw_targets:
                targets.append(normalize_config_target(raw_target, config_path))
        except (OSError, json.JSONDecodeError, ValueError) as error:
            CONFIG_WARNINGS.append(f"{config_path.name}: {error}")

    return targets


