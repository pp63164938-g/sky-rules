def run_rules_check(stage: str, source_only: bool = False) -> None:
    """运行规则仓库自检，失败时阻断同步流程。"""
    if not CHECK_RULES_SCRIPT.exists():
        raise SystemExit(f"规则自检脚本不存在: {CHECK_RULES_SCRIPT}")

    command = [sys.executable, str(CHECK_RULES_SCRIPT)]
    if source_only:
        command.append("--source-only")

    print(f"[规则自检 - {stage}]", flush=True)
    result = subprocess.run(command, cwd=ROOT)
    if result.returncode != 0:
        raise SystemExit(f"规则自检失败，已停止同步（阶段：{stage}）")
    print()


def git_commit_and_push() -> None:
    """自动提交并推送 sky-rules 仓库变更。"""
    print("[1/2] Git 提交变更...")
    os.chdir(ROOT)

    subprocess.run(["git", "add", "-A"], check=True, capture_output=True)

    result = subprocess.run(["git", "diff", "--cached", "--quiet"], capture_output=True)
    if result.returncode != 0:
        subprocess.run(
            ["git", "commit", "-m", "update: sync workflows and rules"],
            check=True,
            capture_output=True,
        )
        push_result = subprocess.run(["git", "push"], capture_output=True, text=True)
        if push_result.returncode == 0:
            print("    OK: 已提交并推送")
        else:
            print("    WARN: 已提交，推送失败（可能无远程或网络问题）")
    else:
        print("    无变更需要提交")
    print()


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    text = text.lstrip("\ufeff")
    if not text.startswith("---"):
        return {}, text

    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}, text

    metadata: dict[str, str] = {}
    for line in parts[1].splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        metadata[key.strip()] = value.strip().strip('"').strip("'")
    return metadata, parts[2].lstrip()


def get_rules_source_files(src: Path) -> list[Path]:
    """读取全局规则源文件列表，支持 manifest 拼接和单文件兼容。"""
    if src.suffix.lower() != ".json":
        return [src]

    raw_config = json.loads(src.read_text(encoding="utf-8"))
    raw_rules = raw_config.get("rules") if isinstance(raw_config, dict) else raw_config
    if not isinstance(raw_rules, list):
        raise ValueError(f"{src.name}: rules 必须是数组")

    rule_files: list[Path] = []
    for index, raw_rule in enumerate(raw_rules, start=1):
        if isinstance(raw_rule, str):
            relative_path = raw_rule
        elif isinstance(raw_rule, dict):
            relative_path = str(raw_rule.get("path", "")).strip()
        else:
            raise ValueError(f"{src.name}: rules[{index}] 必须是字符串或对象")

        if not relative_path:
            raise ValueError(f"{src.name}: rules[{index}].path 不能为空")

        rule_file = (src.parent / relative_path).resolve()
        if not rule_file.exists():
            raise FileNotFoundError(f"{src.name}: 规则源文件不存在: {relative_path}")
        rule_files.append(rule_file)

    return rule_files


def build_rules_content(src: Path, strip_frontmatter: bool = False) -> str:
    """按规则清单拼接全局规则内容。"""
    parts: list[str] = []
    for index, rule_file in enumerate(get_rules_source_files(src)):
        text = rule_file.read_text(encoding="utf-8-sig")

        if index == 0 and not strip_frontmatter:
            parts.append(text.rstrip())
            continue

        _, body = split_frontmatter(text)
        parts.append(body.rstrip())

    return "\n\n".join(part for part in parts if part) + "\n"


def slugify(value: str) -> str:
    value = value.lower().replace(".", "-").replace("_", "-")
    value = re.sub(r"[^a-z0-9-]+", "-", value)
    value = re.sub(r"-+", "-", value).strip("-")
    return value[:63] or "sky-workflow"


def yaml_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def format_source_path(path: Path) -> str:
    """将生成来源路径格式化为仓库相对路径。"""
    resolved_path = path.resolve()
    try:
        return resolved_path.relative_to(ROOT).as_posix()
    except ValueError:
        return resolved_path.as_posix()


def is_generated_sky_workflow_skill(skill_text: str) -> bool:
    """判断 Skill 是否为本仓库工作流生成产物。"""
    if GENERATED_BY_MARKER in skill_text:
        return True

    return (
        SKY_WORKFLOW_DESCRIPTION_MARKER in skill_text
        and SOURCE_WORKFLOW_EDIT_MARKER in skill_text
    )


def iter_sync_source_files(src: Path, pattern: str, exclude: object = None) -> list[Path]:
    """按匹配规则获取源文件，并排除不参与同步的说明文件。"""
    excluded_names = set(as_list(exclude))
    return [src_file for src_file in sorted(src.glob(pattern)) if src_file.name not in excluded_names]


def is_same_file_content(left_file: Path, right_file: Path) -> bool:
    """判断两个文件内容是否一致，用于清理已排除的旧同步残留。"""
    try:
        return left_file.read_bytes() == right_file.read_bytes()
    except OSError:
        return False


def get_workflow_companion_target(item: dict[str, object]) -> Path | None:
    """获取工作流目标中的 project-catalog.json 伴随资源路径。"""
    src = item.get("src")
    if not isinstance(src, Path) or src.resolve() != SRC_WORKFLOWS.resolve():
        return None

    dst = item.get("dst")
    if not isinstance(dst, Path):
        raise ValueError(f"{item['name']}: 工作流目标路径无效")

    mode = str(item.get("mode", ""))
    if mode == "mirror":
        return dst / PROJECT_CATALOG_FILE.name

    if mode == "agents_skills":
        skill_name = slugify(PROJECT_CONTEXT_WORKFLOW_STEM)
        return dst / skill_name / PROJECT_CATALOG_FILE.name

    raise ValueError(f"{item['name']}: 工作流同步模式 {mode} 尚未支持伴随资源")


def get_workflow_skill_names(
    src: Path = SRC_WORKFLOWS,
    pattern: str = "*.md",
    exclude: object = None,
) -> list[str]:
    """获取 workflows 转换后的 Skill 目录名。"""
    if not src.exists():
        return []

    return [slugify(src_file.stem) for src_file in iter_sync_source_files(src, pattern, exclude or ["README.md"])]


def find_codex_cli() -> Path | None:
    """查找可执行的 Codex CLI，避免误用桌面入口 /usr/bin/codex。"""
    candidates: list[str | Path | None] = [
        shutil.which("codex-cli"),
        HOME / ".local" / "bin" / "codex-cli",
        Path("/usr/lib/codex/resources/codex"),
    ]

    for candidate in candidates:
        if not candidate:
            continue
        path = Path(candidate)
        if path.exists() and os.access(path, os.X_OK):
            return path

    return None


def run_codex_prompt_input_probe(expected_skill_names: list[str]) -> tuple[str, str]:
    """通过 Codex 自身 prompt-input 验证 Skills 是否进入模型可见上下文。"""
    codex_cli = find_codex_cli()
    if codex_cli is None:
        return "warn", "未找到 codex-cli，已跳过模型输入验证"

    try:
        result = subprocess.run(
            [str(codex_cli), "debug", "prompt-input", "sky-rules-sync-check"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        return "warn", f"prompt-input 验证未完成: {error}"

    if result.returncode != 0:
        message = (result.stderr or result.stdout).strip().splitlines()
        reason = message[0] if message else f"退出码 {result.returncode}"
        return "warn", f"prompt-input 验证失败: {reason}"

    probe_names = [name for name in expected_skill_names if name in {"base-debugging", "base-docs", "kl-gen-page"}]
    if not probe_names:
        probe_names = expected_skill_names[:3]

    missing = [name for name in probe_names if name not in result.stdout]
    if missing:
        return "fail", f"prompt-input 未看到 Skills: {', '.join(missing)}"

    return "ok", f"prompt-input 可见 Skills: {', '.join(probe_names)}"


def is_file_target(item: dict[str, object]) -> bool:
    """判断同步目标是否是单文件。"""
    return is_file_mode(str(item["mode"]))


def get_env_names(item: dict[str, object]) -> list[str]:
    """获取影响当前目标路径的环境变量名。"""
    return list(item.get("exact_env", [])) + list(item.get("base_env", []))


def has_target_env(item: dict[str, object]) -> bool:
    """判断当前目标是否由环境变量显式配置。"""
    return any(os.environ.get(env_name) for env_name in get_env_names(item))


def should_sync_target(item: dict[str, object], include_missing_targets: bool) -> bool:
    """判断目标是否应该同步。未检测到且未显式配置的工具默认跳过。"""
    if include_missing_targets:
        return True

    if has_target_env(item):
        return True

    detect_path = item.get("detect")
    if isinstance(detect_path, Path):
        return detect_path.exists()

    return True


def get_skip_reason(item: dict[str, object]) -> str:
    """生成未检测到工具时的跳过说明。"""
    detect_path = item.get("detect")
    if isinstance(detect_path, Path):
        return f"未检测到工具目录 ({detect_path})"

    return "未检测到工具目录"


def get_target_source(item: dict[str, object]) -> str:
    """获取目标路径来源：精确变量、根目录变量或默认路径。"""
    for env_name in item.get("exact_env", []):
        if os.environ.get(env_name):
            return f"{env_name}"

    for env_name in item.get("base_env", []):
        if os.environ.get(env_name):
            return f"{env_name} + 默认子路径"

    if item.get("config"):
        return f"{item['config']} 默认路径"

    return "默认路径"


def print_config_warnings() -> None:
    """输出扩展配置读取警告。"""
    if not CONFIG_WARNINGS:
        return

    print("[配置警告]")
    for warning in CONFIG_WARNINGS:
        print(f"  WARN {warning}")
    print()


def get_existing_parent(path: Path) -> Path | None:
    """查找离目标最近的已存在父目录。"""
    current_path = path
    while not current_path.exists():
        parent_path = current_path.parent
        if parent_path == current_path:
            return None
        current_path = parent_path

    if current_path.is_file():
        return current_path.parent

    return current_path


